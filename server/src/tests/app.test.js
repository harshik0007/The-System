test('startup diagnostics preserve useful details while redacting connection credentials', () => {
  const calls = [];
  const error = new Error('Could not connect to mongodb://member:private-password@127.0.0.1:27017/the-system?replicaSet=rs0');
  logStartupError(error, { nodeEnv: 'development', logger: (...args) => calls.push(args) });

  assert.equal(calls.length, 1);
  assert.equal(calls[0][0], '[api-startup-error]');
  const diagnostics = JSON.parse(calls[0][1]);
  assert.equal(diagnostics.errorName, 'Error');
  assert.match(diagnostics.message, /\[redacted MongoDB URI\]/);
  assert.equal(JSON.stringify(diagnostics).includes('private-password'), false);
  assert.match(diagnostics.stack, /Could not connect/);
});
