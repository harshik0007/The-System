function responseStub() {
  return {
    headers: {},
    statusCode: 200,
    body: undefined,
    setHeader(name, value) { this.headers[name.toLowerCase()] = value; },
    status(value) { this.statusCode = value; return this; },
    json(value) { this.body = value; return this; },
    sendStatus(value) { this.statusCode = value; return this; },
  };
}

function routeHandler(app, path, method = 'get') {
  const layer = app._router.stack.find((item) => item.route?.path === path && item.route.methods[method]);
  assert.ok(layer, `Expected ${method.toUpperCase()} ${path} route`);
  return layer.route.stack.at(-1).handle;
}

test('liveness stays healthy while readiness reports the unavailable database', () => {
  const app = createApp({ databaseReady: () => false });
  const healthRequest = { requestId: 'health-request' };
  const healthResponse = responseStub();
  routeHandler(app, '/api/health')(healthRequest, healthResponse);
  assert.equal(healthResponse.statusCode, 200);
  assert.equal(healthResponse.body.status, 'ok');

  const readyResponse = responseStub();
  routeHandler(app, '/api/ready')({ requestId: 'ready-request' }, readyResponse);
  assert.equal(readyResponse.statusCode, 503);
  assert.equal(readyResponse.body.status, 'not_ready');
  assert.deepEqual(readyResponse.body.dependencies, { database: 'unavailable' });
  assert.equal(JSON.stringify(readyResponse.body).includes('mongodb://'), false);
});

test('readiness reports ready only when the database probe is ready', () => {
  const app = createApp({ databaseReady: () => true });
  const response = responseStub();
  routeHandler(app, '/api/ready')({ requestId: 'ready-request' }, response);
  assert.equal(response.statusCode, 200);
  assert.equal(response.body.status, 'ready');
});

test('auth state is public, private identity needs a validated session, and dev whoami is absent', async () => {
  const routeError = await new Promise((resolve) => requireAuthenticatedUser({}, {}, resolve));
  assert.equal(routeError.status, 401);
  const meResponse = responseStub();
  await createAuthController({ service: { currentMember: async () => null } }).me({ authMember: null }, meResponse);
  assert.equal(meResponse.statusCode, 200);
  assert.deepEqual(meResponse.body, { authenticated: false, member: null });

  const api = createApiV1Router();
  const mounted = api.stack.map((layer) => layer.handle?.stack || []).flat();
  assert.equal(mounted.some((layer) => layer.route?.path === '/dev/whoami'), false);
  assert.equal(createApp({ nodeEnv: 'test', databaseReady: () => true }) !== null, true);
});

test('request IDs are generated by the server and common security headers are set', () => {
  const request = { headers: { 'x-request-id': 'untrusted-id' } };
  const response = responseStub();
  let continued = false;
  requestIdMiddleware(request, response, () => { continued = true; });
  assert.match(request.requestId, /^[0-9a-f-]{36}$/i);
  assert.equal(request.requestId, response.headers['x-request-id']);
  assert.notEqual(request.requestId, 'untrusted-id');
  securityHeaders(request, response, () => {});
  assert.equal(response.headers['x-content-type-options'], 'nosniff');
  assert.equal(response.headers['x-frame-options'], 'DENY');
  assert.equal(continued, true);
});

test('not-found and malformed body errors return safe request-ID responses', () => {
  const request = { requestId: 'error-request' };
  let missingError;
  notFoundHandler(request, {}, (error) => { missingError = error; });
  const missingResponse = responseStub();
  errorHandler(missingError, request, missingResponse, () => {});
  assert.equal(missingResponse.statusCode, 404);
  assert.equal(missingResponse.body.error.code, 'NOT_FOUND');
  assert.equal(missingResponse.body.error.requestId, 'error-request');

  const malformedResponse = responseStub();
  errorHandler({ type: 'entity.parse.failed' }, request, malformedResponse, () => {});
  assert.equal(malformedResponse.statusCode, 400);
  assert.equal(malformedResponse.body.error.code, 'INVALID_JSON');
});

test('internal errors log correlation and development stack while keeping the API response safe', () => {
  const originalEnv = process.env.NODE_ENV;
  const originalError = console.error;
  const logCalls = [];
  process.env.NODE_ENV = 'development';
  console.error = (...args) => logCalls.push(args);
  try {
    const error = new Error('transaction failed');
    const response = responseStub();
    errorHandler(error, {
      requestId: 'schedule-request-id',
      method: 'POST',
      baseUrl: '/api/v1',
      route: { path: '/task-schedules' },
    }, response, () => {});

    assert.equal(response.statusCode, 500);
    assert.equal(response.body.error.requestId, 'schedule-request-id');
    assert.equal(response.body.error.message, 'An unexpected server error occurred.');
    assert.equal(JSON.stringify(response.body).includes('transaction failed'), false);
    assert.equal(logCalls.length, 1);
    assert.equal(logCalls[0][0], '[api-error]');
    const diagnostics = JSON.parse(logCalls[0][1]);
    assert.equal(diagnostics.requestId, 'schedule-request-id');
    assert.equal(diagnostics.method, 'POST');
    assert.equal(diagnostics.route, '/api/v1/task-schedules');
    assert.equal(diagnostics.errorName, 'Error');
    assert.equal(diagnostics.message, 'transaction failed');
    assert.match(diagnostics.stack, /transaction failed/);
  } finally {
    console.error = originalError;
    if (originalEnv === undefined) delete process.env.NODE_ENV;
    else process.env.NODE_ENV = originalEnv;
  }
});

test('CORS reflects configured exact origins and rejects other browser origins', () => {
  const cors = createCorsMiddleware(['https://client.example', 'http://localhost:5176', 'http://127.0.0.1:5176']);
  const acceptedResponse = responseStub();
  cors({ method: 'GET', get: () => 'https://client.example' }, acceptedResponse, () => {});
  assert.equal(acceptedResponse.headers['access-control-allow-origin'], 'https://client.example');

  const devResponse = responseStub();
  cors({ method: 'GET', get: () => 'http://localhost:5176' }, devResponse, () => {});
  assert.equal(devResponse.headers['access-control-allow-origin'], 'http://localhost:5176');
  assert.equal(devResponse.headers['access-control-allow-credentials'], 'true');

  let denied;
  cors({ method: 'GET', get: () => 'https://other.example' }, responseStub(), (error) => { denied = error; });
  assert.equal(denied.status, 403);
  let untrustedLocalPort;
  cors({ method: 'GET', get: () => 'http://localhost:5200' }, responseStub(), (error) => { untrustedLocalPort = error; });
  assert.equal(untrustedLocalPort.status, 403);
});

test('central request validation rejects invalid input without echoing field values', () => {
  const middleware = validateRequest(({ body }) => body?.count >= 0 ? [] : ['count must be non-negative']);
  let validationError;
  middleware({ body: { count: -99 }, params: {}, query: {} }, {}, (error) => { validationError = error; });
  const response = responseStub();
  errorHandler(validationError, { requestId: 'validation-request' }, response, () => {});
  assert.equal(response.statusCode, 400);
  assert.equal(response.body.error.code, 'VALIDATION_ERROR');
  assert.equal(JSON.stringify(response.body).includes('-99'), false);
});

